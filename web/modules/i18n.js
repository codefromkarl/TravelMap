// ─── 应用多语言 ─────────────────────────────────────────
export function applyI18n(lang) {
  const dict = I18N[lang] || I18N.zh;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    if (dict[key]) el.title = dict[key];
  });
  const ta = document.querySelector("message-editor textarea");
  if (ta) {
    ta.placeholder = dict.promptPlaceholder || "描述你的旅行计划...";
    ta.title = dict.sendTitle || "发送消息";
  }
  document.querySelectorAll(".disabled-ghost").forEach(el => {
    el.title = dict.exportDisabled || "生成行程后可用";
  });
  document.querySelectorAll(".close-btn").forEach(el => {
    el.setAttribute("aria-label", dict.closeAria || "关闭");
  });
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  const langMap = { zh: "zh-CN", en: "en", ja: "ja" };
  document.documentElement.lang = langMap[lang] || "zh-CN";
}

// ─── 初始化 placeholder ─────────────────────────────────
export function initPlaceholder() {
  const ta = document.querySelector("message-editor textarea");
  if (ta) {
    const dict = I18N[currentLang] || I18N.zh;
    ta.placeholder = dict.promptPlaceholder || "描述你的旅行计划...";
  }
}